#!/usr/bin/env node
/**
 * Generates apps/companion-pwa/public/firebase-messaging-sw.js from .env.local,
 * substituting real Firebase config values before every build.
 *
 * WHY THIS SCRIPT EXISTS:
 *   Vite's public/ directory is copied to dist/ verbatim — no env var
 *   substitution happens there, unlike src/ files which go through Vite's
 *   `import.meta.env` processing. A Firebase Messaging service worker MUST
 *   be a plain, unbundled script at a fixed root path (see the generated
 *   file's own header comment for why), so it can't use import.meta.env
 *   directly. This script is the bridge: read .env.local like Vite would,
 *   write the real values into the one file that can't use Vite's normal
 *   env mechanism.
 *
 * NOTE ON FIREBASE CONFIG NOT BEING SECRET:
 *   apiKey/authDomain/projectId etc. are public client identifiers by
 *   Firebase's own design — real security comes from Firestore rules and
 *   Auth, not from hiding these values. Baking them into a served static
 *   file is standard practice, not a security compromise.
 *
 * Run automatically via the `prebuild`/`predev` npm scripts in package.json
 * — you should never need to run this by hand.
 */

import { readFileSync, writeFileSync, existsSync } from 'fs';
import { fileURLToPath } from 'url';
import path from 'path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(__dirname, '..');
const envPath = path.join(projectRoot, '.env.local');
const outputPath = path.join(projectRoot, 'public', 'firebase-messaging-sw.js');

function parseEnvFile(filePath) {
  if (!existsSync(filePath)) return {};

  const content = readFileSync(filePath, 'utf-8');
  const vars = {};

  for (const line of content.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    const value = trimmed.slice(eq + 1).trim();
    vars[key] = value;
  }

  return vars;
}

// Check process.env FIRST — in GitHub Actions, secrets are injected directly
// as environment variables, and no .env.local file exists on the CI runner
// at all. Locally, developers have a real .env.local file but plain Node
// scripts (unlike Vite-processed app code) don't read it automatically, so
// parseEnvFile() is the fallback for that case. This single function needs
// to work correctly in both environments.
const fileVars = parseEnvFile(envPath);
const env = { ...fileVars, ...process.env };

const required = [
  'VITE_FIREBASE_API_KEY',
  'VITE_FIREBASE_AUTH_DOMAIN',
  'VITE_FIREBASE_PROJECT_ID',
  'VITE_FIREBASE_STORAGE_BUCKET',
  'VITE_FIREBASE_MESSAGING_SENDER_ID',
  'VITE_FIREBASE_APP_ID',
];

const missing = required.filter((key) => !env[key]);
if (missing.length > 0) {
  console.error(
    `\n[generate-messaging-sw] Missing values: ${missing.join(', ')}\n` +
    `Set these as environment variables (CI) or in .env.local (local dev).\n`,
  );
  process.exit(1);
}

const swContent = `/**
 * Firebase Cloud Messaging service worker.
 * AUTO-GENERATED by scripts/generate-messaging-sw.mjs from .env.local — do not edit directly.
 * Edit .env.local and rebuild instead; this file is regenerated on every build.
 *
 * Registers a background handler so a push notification is shown even when
 * this page isn't open/focused on the phone.
 */

importScripts('https://www.gstatic.com/firebasejs/10.14.1/firebase-app-compat.js');
importScripts('https://www.gstatic.com/firebasejs/10.14.1/firebase-messaging-compat.js');

firebase.initializeApp({
  apiKey: '${env.VITE_FIREBASE_API_KEY}',
  authDomain: '${env.VITE_FIREBASE_AUTH_DOMAIN}',
  projectId: '${env.VITE_FIREBASE_PROJECT_ID}',
  storageBucket: '${env.VITE_FIREBASE_STORAGE_BUCKET}',
  messagingSenderId: '${env.VITE_FIREBASE_MESSAGING_SENDER_ID}',
  appId: '${env.VITE_FIREBASE_APP_ID}',
});

const messaging = firebase.messaging();

messaging.onBackgroundMessage((payload) => {
  const title = payload.notification?.title ?? 'Claude is ready';
  const body = payload.notification?.body ?? 'Your session has reset';

  self.registration.showNotification(title, {
    body,
    icon: '/icons/icon192.png',
    badge: '/icons/icon192.png',
    data: { url: 'https://claude.ai' },
  });
});

self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  const url = event.notification.data?.url ?? 'https://claude.ai';
  event.waitUntil(clients.openWindow(url));
});
`;

writeFileSync(outputPath, swContent, 'utf-8');
console.log(`[generate-messaging-sw] Wrote ${outputPath}`);
